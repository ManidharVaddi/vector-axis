def show_login_page():
    st.title("Vector Axis")

    with st.expander("👀 See how Vector Axis works (no account needed)"):
        st.caption("This is example data generated by the app's own logic - not a real account.")
        demo = generate_demo_history(days=30)

        demo_fig = build_radar_chart(demo["categories"], color=COLOR_PALETTE[DEFAULT_RADAR_COLOR_NAME])
        st.plotly_chart(demo_fig, use_container_width=True, key="preview_radar")

        pie_fig = build_weekly_pie_chart(demo["weekly_summary"][-1])
        st.plotly_chart(pie_fig, use_container_width=True, key="preview_pie")

        bar_fig = build_weekly_bar_chart(demo["weekly_summary"])
        st.plotly_chart(bar_fig, use_container_width=True, key="preview_bar")

        line_fig = build_monthly_line_chart(demo["daily_scores"], line_color=COLOR_PALETTE[DEFAULT_LINE_COLOR_NAME])
        st.plotly_chart(line_fig, use_container_width=True, key="preview_line")

    st.subheader("Log In")

    username = st.text_input("Username", key="login_username")
    password = st.text_input("Password", type="password", key="login_password")

    if st.button("Log In", use_container_width=True):
        success, msg, user = login_user(username, password)
        if success:
            st.session_state.logged_in = True
            st.session_state.user = user
            st.rerun()
        else:
            st.error(msg)

    st.write("Don't have an account?")
    if st.button("Register here", use_container_width=True):
        st.session_state.auth_mode = "register"
        st.rerun()


def show_register_page():
    st.title("Vector Axis")
    st.subheader("Create Account")

    username = st.text_input("Choose a Username", key="reg_username")
    password = st.text_input("Choose a Password", type="password", key="reg_password")
    confirm = st.text_input("Confirm Password", type="password", key="reg_confirm")

    if st.button("Create Account", use_container_width=True):
        if password != confirm:
            st.error("Passwords do not match.")
        else:
            success, msg = register_user(username, password)
            if success:
                st.success(msg + " Please log in.")
                st.session_state.auth_mode = "login"
                st.rerun()
            else:
                st.error(msg)

    st.write("Already have an account?")
    if st.button("Log in here", use_container_width=True):
        st.session_state.auth_mode = "login"
        st.rerun()




def show_onboarding_step1():
    st.title("Set up your Axis")
    st.write("Good + Bad habits must total 10 or less")

    good_count = st.number_input("How many GOOD habits do you want to track?", min_value=0, max_value=10, step=1, key="good_count_input")
    bad_count = st.number_input("How many BAD habits do you want to track?", min_value=0, max_value=10, step=1, key="bad_count_input")

    error_slot = st.empty()

    if st.button("Next", use_container_width=True):
        if good_count + bad_count == 0:
            error_slot.error("Add at least 1 category.")
        elif good_count + bad_count > 10:
            error_slot.error("Good + Bad must be 10 or less.")
        else:
            st.session_state.good_count = int(good_count)
            st.session_state.bad_count = int(bad_count)
            st.session_state.onboarding_step = 2
            st.rerun()


def show_onboarding_step2():
    st.title("Enter what you want to make a habit")

    good_names = []
    for i in range(st.session_state.good_count):
        name = st.text_input(f"Good habit {i + 1}", key=f"good_name_{i}", placeholder="Type a habit name")
        good_names.append(name)

    error_slot = st.empty()

    if st.button("Next", use_container_width=True):
        if any(not n.strip() for n in good_names):
            error_slot.error("Fill in all good habit names.")
        else:
            st.session_state.good_names = good_names
            st.session_state.onboarding_step = 3
            st.rerun()


def show_onboarding_step3():
    st.title("Enter what you want to stop")

    bad_names = []
    for i in range(st.session_state.bad_count):
        name = st.text_input(f"Bad habit {i + 1}", key=f"bad_name_{i}", placeholder="Type a habit name")
        bad_names.append(name)

    error_slot = st.empty()

    if st.button("Finish Setup", use_container_width=True):
        if any(not n.strip() for n in bad_names):
            error_slot.error("Fill in all bad habit names.")
        else:
            save_categories(st.session_state.user["id"], st.session_state.good_names, bad_names)
            mark_onboarding_complete(st.session_state.user["id"])
            st.session_state.user["onboarding_complete"] = True
            st.session_state.onboarding_step = 1  # reset for safety
            st.rerun()
def show_home_page():
    mark_app_opened_today(st.session_state.user["id"])

    st.title("Vector Axis")
    st.write(f"Welcome back, **{st.session_state.user['username']}**!")

    created_date = date_cls.fromisoformat(st.session_state.user["created_at"][:10])
    penalties = check_and_apply_missed_days(st.session_state.user["id"], created_date)
    if penalties > 0:
        st.warning(f"You missed checking in on {penalties} day(s). Your Axis was affected — silence hurts more than an honest bad day.")

    categories = get_categories(st.session_state.user["id"])

    radar_color_name = st.selectbox(
        "Radar color",
        list(COLOR_PALETTE.keys()),
        index=list(COLOR_PALETTE.keys()).index(st.session_state.radar_color_name),
        key="radar_color_select",
    )
    st.session_state.radar_color_name = radar_color_name

    fig = build_radar_chart(categories, color=COLOR_PALETTE[radar_color_name])
    st.plotly_chart(fig, use_container_width=True)

    suggestion = get_top_suggestion(st.session_state.user["id"])
    if suggestion:
        st.markdown("### 🧠 AI Insight")
        if suggestion["mode"] == "heuristic":
            st.info(suggestion["message"])
        else:
            st.warning(suggestion["message"])

    st.write("Raw values (for verification):")
    for cat in categories:
        st.write(f"- **{cat['name']}** ({cat['type']}) — score: {cat['score']:.1f}")

    st.divider()

    if is_checkin_window_open():
        if has_checked_in_today(st.session_state.user["id"]):
            st.success("✅ You've already checked in today. See you tomorrow!")
        else:
            st.success("🟢 Check-in window open (9–11 PM IST)")
            if st.button("Check In for Today", use_container_width=True):
                st.session_state.page = "checkin"
                st.rerun()
    else:
        st.info(f"🔒 View only — check-in opens at 9 PM IST. (Current IST time: {get_ist_now().strftime('%I:%M %p')})")

    if st.button("View Insights (Pie, Bar, Line Charts)", use_container_width=True):
        st.session_state.page = "insights"
        st.rerun()

    if st.button("View Consistency Tracker", use_container_width=True):
        st.session_state.page = "consistency"
        st.rerun()

    if st.button("Log Out"):
        st.session_state.logged_in = False
        st.session_state.user = None
        st.rerun()
def show_checkin_page():
    if not is_checkin_window_open():
        st.error("Check-in is only available between 9 PM and 11 PM IST.")
        if st.button("Back to Axis"):
            st.session_state.page = "home"
            st.rerun()
        return

    if has_checked_in_today(st.session_state.user["id"]):
        st.info("You've already checked in today. Come back tomorrow between 9–11 PM IST.")
        if st.button("Back to Axis"):
            st.session_state.page = "home"
            st.rerun()
        return

    st.title("Today's Check-in")
    st.write("This submission updates your Axis.")

    categories = get_categories(st.session_state.user["id"])
    ticks = {}

    for cat in categories:
        tag = "🟢 Good" if cat["type"] == "good" else "🔴 Bad"
        label = f"{cat['name']} ({tag})"
        ticks[cat["id"]] = st.checkbox(label, key=f"tick_{cat['id']}")

    if st.button("Submit", use_container_width=True):
        submit_daily_checkin(st.session_state.user["id"], ticks)
        st.success("Check-in submitted! Your Axis has been updated.")
        st.session_state.page = "home"
        st.rerun()

def show_consistency_page():
    st.title("Consistency Tracker")

    streak = get_current_streak(st.session_state.user["id"])
    st.metric("Current Streak", f"{streak} day{'s' if streak != 1 else ''}")

    st.write("Last 30 days:")
    log = get_activity_log(st.session_state.user["id"], days_back=30)

    color_map = {
        "submitted": "🟩",
        "opened_no_submit": "⬜",
        "penalty_applied": "🟥",
        None: "⬛",
    }

    # Render as a simple grid, 7 per row (like a calendar week)
    cols_per_row = 7
    for i in range(0, len(log), cols_per_row):
        row = log[i:i + cols_per_row]
        cols = st.columns(cols_per_row)
        for col, entry in zip(cols, row):
            symbol = color_map.get(entry["state"], "⬛")
            col.markdown(f"<div style='text-align:center'>{symbol}<br><small>{entry['date'].strftime('%d/%m')}</small></div>", unsafe_allow_html=True)

    st.caption("🟩 Checked in · 🟥 Missed entirely (penalty applied) · ⬛ No record yet")
    st.write("Missing a day affects your Axis more than an honest bad day would.")

    if st.button("Back to Axis"):
        st.session_state.page = "home"
        st.rerun()



