def show_insights_page():
    st.title("Insights")

    user_id = st.session_state.user["id"]
    weekly_summary = get_weekly_summary(user_id, weeks_back=5)
    daily_scores = get_daily_scores(user_id, days_back=30)

    # Determine if there's enough real data, or if we should show demo data instead
    has_real_data = any(w["good_count"] + w["bad_count"] > 0 for w in weekly_summary)

    if not has_real_data:
        st.info("📊 No check-in data yet - showing example data so you can see how Insights works. Your real data will replace this as you check in.")
        demo = generate_demo_history(days=30)
        weekly_summary = demo["weekly_summary"]
        daily_scores = demo["daily_scores"]

    # --- Weekly Pie Chart ---
    st.subheader("Weekly Breakdown")
    week_labels = [w["week_start"].strftime("%d %b %Y") for w in weekly_summary]
    selected_label = st.selectbox("Select week", week_labels, index=len(week_labels) - 1)
    selected_week = weekly_summary[week_labels.index(selected_label)]
    pie_fig = build_weekly_pie_chart(selected_week)
    st.plotly_chart(pie_fig, use_container_width=True)

    # --- Weekly Bar Chart ---
    st.subheader("Weekly Performance")
    bar_fig = build_weekly_bar_chart(weekly_summary)
    st.plotly_chart(bar_fig, use_container_width=True)

    # --- Monthly Line Chart ---
    st.subheader("Monthly Trend")
    line_color_name = st.selectbox(
        "Line color",
        list(COLOR_PALETTE.keys()),
        index=list(COLOR_PALETTE.keys()).index(st.session_state.line_color_name),
        key="line_color_select",
    )
    st.session_state.line_color_name = line_color_name
    line_fig = build_monthly_line_chart(daily_scores, line_color=COLOR_PALETTE[line_color_name])
    st.plotly_chart(line_fig, use_container_width=True)

    if st.button("Back to Axis"):
        st.session_state.page = "home"
        st.rerun()


